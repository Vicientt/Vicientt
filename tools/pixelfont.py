CELL_W = 6          # 5 pixels of glyph + 1 of tracking
CELL_H = 7


def text_width(s, px):
    return len(s) * CELL_W * px


def emit(s, x, y, px, fill=None, cls=None):
    """Return SVG rects for `s`, top-left anchored at (x, y)."""
    parts = []
    attrs = ""
    if fill:
        attrs += f' fill="{fill}"'
    if cls:
        attrs += f' class="{cls}"'
    parts.append(f"<g{attrs}>")
    cx = x
    for ch in s.upper():
        rows = FONT.get(ch)
        if rows:
            for r, row in enumerate(rows):
                run = 0
                for c in range(6):
                    on = c < len(row) and row[c] == "1"
                    if on:
                        run += 1
                    elif run:
                        parts.append(
                            f'<rect x="{cx + (c - run) * px:.1f}" y="{y + r * px:.1f}" '
                            f'width="{run * px:.1f}" height="{px}"/>'
                        )
                        run = 0
                if run:
                    parts.append(
                        f'<rect x="{cx + (6 - run) * px:.1f}" y="{y + r * px:.1f}" '
                        f'width="{run * px:.1f}" height="{px}"/>'
                    )
        cx += CELL_W * px
    parts.append("</g>")
    return "".join(parts)


def wrap(s, max_chars):
    """Greedy wrap on word boundaries."""
    words, lines, cur = s.split(), [], ""
    for w in words:
        cand = f"{cur} {w}".strip()
        if len(cand) > max_chars and cur:
            lines.append(cur)
            cur = w
        else:
            cur = cand
    if cur:
        lines.append(cur)
    return lines
